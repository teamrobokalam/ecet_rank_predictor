
import streamlit as st
import pickle
import numpy as np
import pandas as pd

# Load trained ML models
with open("integrated_rank_model.pkl", "rb") as file:
    integrated_model, integrated_columns = pickle.load(file)

with open("branch_rank_model.pkl", "rb") as file:
    branch_model, branch_columns = pickle.load(file)


# Prediction function
def predict_ranks(year, maths, physics, chemistry, core, branch):

    values = {
        "Year": year,
        "Mathematics_Marks": maths,
        "Physics_Marks": physics,
        "Chemistry_Marks": chemistry,
        "Engineering_Marks": core,
        "Diploma_Branch": branch
    }

    # Convert input into DataFrame
    input_data = pd.DataFrame([values])

    # Convert branch name into numerical columns
    input_data = pd.get_dummies(
        input_data,
        columns=["Diploma_Branch"]
    )

    # Match the columns used during model training
    input_data = input_data.reindex(
        columns=integrated_columns,
        fill_value=0
    )

    integrated_rank = integrated_model.predict(input_data)[0]

    # Prepare input for branch rank model
    branch_input = pd.DataFrame([values])

    branch_input = pd.get_dummies(
        branch_input,
        columns=["Diploma_Branch"]
    )

    branch_input = branch_input.reindex(
        columns=branch_columns,
        fill_value=0
    )

    branch_rank = branch_model.predict(branch_input)[0]

    return round(integrated_rank), round(branch_rank)


# Main function
def main():

    st.set_page_config(
        page_title="TS ECET Rank Predictor",
        page_icon="🎓",
        layout="centered"
    )

    st.title("🎓 TS ECET Rank Predictor")

    template = """
    <div style="background-color:#1565C0; padding:18px; border-radius:10px;">
        <h1 style="color:white; text-align:center;">
            TS ECET Rank Predictor
        </h1>
        <p style="color:white; text-align:center;">
            Predict your Integrated Rank and Branch Rank
        </p>
    </div>
    """

    st.markdown(template, unsafe_allow_html=True)

    st.write("")
    st.subheader("Enter Your Examination Details")

    # Student details
    year = st.selectbox(
        "Examination Year",
        [2022, 2023, 2024, 2025, 2026],
        index=4
    )

    branch = st.selectbox(
        "Select Your Diploma Branch",
        ["CSE", "ECE", "EEE", "MECH", "CIVIL", "OTHER"]
    )

    st.write("### Enter Your Marks")

    maths = st.number_input(
        "Mathematics Marks (out of 50)",
        min_value=0.0,
        max_value=50.0,
        value=0.0
    )

    physics = st.number_input(
        "Physics Marks (out of 25)",
        min_value=0.0,
        max_value=25.0,
        value=0.0
    )

    chemistry = st.number_input(
        "Chemistry Marks (out of 25)",
        min_value=0.0,
        max_value=25.0,
        value=0.0
    )

    core = st.number_input(
        "Core / Engineering Marks (out of 100)",
        min_value=0.0,
        max_value=100.0,
        value=0.0
    )

    st.write("")

    if st.button("Predict My Rank", use_container_width=True):

        try:
            integrated_rank, branch_rank = predict_ranks(
                year,
                maths,
                physics,
                chemistry,
                core,
                branch
            )

            st.success("Prediction completed!")

            st.subheader("Your Predicted Results")

            col1, col2 = st.columns(2)

            with col1:
                st.metric(
                    label="Integrated Rank",
                    value=integrated_rank
                )

            with col2:
                st.metric(
                    label="Branch Rank",
                    value=branch_rank
                )

            st.info(
                "These ranks are estimates generated by a machine learning model. "
                "They are not official TS ECET ranks."
            )

        except Exception as e:
            st.error("Prediction error: {}".format(e))


if __name__ == "__main__":
    main()
